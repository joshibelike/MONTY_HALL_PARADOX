const fs = require('node:fs');
const path = require('node:path');
const { playRound } = require('../js/monty-hall.js');

const GAMES_PER_STRATEGY = 10_000;
const SEED = 2026;
const CHECKPOINT_STEP = 50;

const ROOT = path.resolve(__dirname, '..');
const REPORT_PATH = path.join(ROOT, 'results.txt');
const DATA_PATH = path.join(ROOT, 'js', 'simulation-data.js');

const STRATEGIES = [
  { id: 'stay', label: 'Оставить выбор', theory: 100 / 3 },
  { id: 'switch', label: 'Поменять дверь', theory: 200 / 3 },
];

function createRng(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const round = (value, digits) => Number(value.toFixed(digits));

function runStrategy({ id, label, theory }, rng) {
  const curve = [];
  let wins = 0;

  for (let game = 1; game <= GAMES_PER_STRATEGY; game++) {
    if (playRound(id, rng).won) wins++;
    if (game % CHECKPOINT_STEP === 0) curve.push(round((wins / game) * 100, 2));
  }

  return {
    id,
    label,
    games: GAMES_PER_STRATEGY,
    wins,
    rate: round((wins / GAMES_PER_STRATEGY) * 100, 2),
    theory: round(theory, 2),
    curve,
  };
}

const formatInteger = (value) => String(value).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
const formatPercent = (value) => `${value.toFixed(2).replace('.', ',')}%`;
const formatSigned = (value) =>
  `${value >= 0 ? '+' : '−'}${Math.abs(value).toFixed(2).replace('.', ',')} п.п.`;

function buildReport(results) {
  const [stay, switching] = results;
  const header = ['Стратегия', 'Игр', 'Побед', 'Доля побед', 'Теория', 'Отклонение'];
  const rows = results.map((r) => [
    r.label,
    formatInteger(r.games),
    formatInteger(r.wins),
    formatPercent(r.rate),
    formatPercent(r.theory),
    formatSigned(r.rate - r.theory),
  ]);

  const widths = header.map((title, i) =>
    Math.max(title.length, ...rows.map((row) => row[i].length)),
  );
  const line = (cells) => `  ${cells.map((cell, i) => cell.padEnd(widths[i])).join('   ')}`;
  const divider = line(widths.map((width) => '-'.repeat(width)));

  return [
    'ПАРАДОКС МОНТИ ХОЛЛА — РЕЗУЛЬТАТЫ СИМУЛЯЦИИ',
    '='.repeat(43),
    '',
    'Условия',
    '  Дверей: 3 (один автомобиль и две козы)',
    `  Игр на каждую стратегию: ${formatInteger(GAMES_PER_STRATEGY)}`,
    `  Генератор случайных чисел: mulberry32, seed ${SEED}`,
    '  Ведущий знает, где приз, всегда открывает невыбранную дверь с козой',
    '  и всегда предлагает сменить выбор.',
    '',
    'Результаты',
    line(header),
    divider,
    ...rows.map(line),
    '',
    'Итог',
    `  Оставляя выбор, выигрывают в ${formatPercent(stay.rate)} игр.`,
    `  Меняя дверь, выигрывают в ${formatPercent(switching.rate)} игр.`,
    `  Смена двери срабатывает в ${(switching.wins / stay.wins).toFixed(2).replace('.', ',')} раза чаще.`,
    '  Теоретические значения: 1/3 (33,33%) без смены и 2/3 (66,67%) со сменой.',
    '',
  ].join('\n');
}

function buildDataModule(results) {
  const [stay, switching] = results;
  const payload = {
    games: GAMES_PER_STRATEGY,
    seed: SEED,
    checkpointStep: CHECKPOINT_STEP,
    strategies: { stay, switch: switching },
  };

  return [
    '// Generated by scripts/simulate.js. Run `node scripts/simulate.js` to refresh.',
    `window.MONTY_HALL_SIMULATION = ${JSON.stringify(payload)};`,
    '',
  ].join('\n');
}

const rng = createRng(SEED);
const results = STRATEGIES.map((strategy) => runStrategy(strategy, rng));

fs.writeFileSync(REPORT_PATH, buildReport(results), 'utf8');
fs.writeFileSync(DATA_PATH, buildDataModule(results), 'utf8');

console.log(fs.readFileSync(REPORT_PATH, 'utf8'));
